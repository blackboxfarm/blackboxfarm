interface EmojiPickerPopoverProps {
  onPick: (emoji: string) => void;
}

export function EmojiPickerPopover({ onPick }: EmojiPickerPopoverProps) {
  const [active, setActive] = useState(0);
  const [query, setQuery] = useState('');

  const list = query.trim()
    ? CATEGORIES.flatMap(c => c.emojis).filter(e => e.includes(query.trim()))
    : CATEGORIES[active].emojis;

  return (
    <Popover>
      <PopoverTrigger asChild>
        <button
          type="button"
          className="inline-flex items-center justify-center rounded-md p-1.5 text-muted-foreground hover:text-yellow-500 hover:bg-yellow-500/10 transition"
          title="Insert emoji"
          aria-label="Insert emoji"
        >
          <Smile className="w-4 h-4" />
        </button>
      </PopoverTrigger>
      <PopoverContent className="w-80 p-0" align="start">
        <div className="border-b border-border p-2">
          <input
            type="text"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Type/paste an emoji to filter…"
            className="w-full text-xs px-2 py-1 rounded bg-muted/40 focus:outline-none focus:ring-1 focus:ring-yellow-500/40"
          />
        </div>
        {!query.trim() && (
          <div className="flex gap-1 px-2 py-1.5 border-b border-border overflow-x-auto">
            {CATEGORIES.map((c, i) => (
              <button
                key={c.label}
                type="button"
                onClick={() => setActive(i)}
                className={`text-[10px] uppercase tracking-wider px-2 py-1 rounded whitespace-nowrap transition ${
                  i === active
                    ? 'bg-yellow-500/15 text-yellow-500'
                    : 'text-muted-foreground hover:text-foreground'
                }`}
              >
                {c.label}
              </button>
            ))}
          </div>
        )}
        <div className="grid grid-cols-8 gap-0.5 p-2 max-h-64 overflow-y-auto">
          {list.map((e, i) => (
            <button
              key={`${e}-${i}`}
              type="button"
              onClick={() => onPick(e)}
              className="text-xl leading-none p-1 rounded hover:bg-muted transition"
              title={e}
            >
              {e}
            </button>
          ))}
          {list.length === 0 && (
            <div className="col-span-8 text-xs text-muted-foreground text-center py-4">No matches</div>
          )}
        </div>
      </PopoverContent>
    </Popover>
  );
}